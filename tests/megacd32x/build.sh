#!/bin/sh
# Builds the Mega CD 32X test program into megacd32x_program.h: the start of a stand-in
# Mega CD BIOS for the console's 68000, with the SH-2s' program inside. Needs the 68000
# binutils (Debian/Ubuntu: apt install binutils-m68k-linux-gnu). The header is
# committed, so the tests do not.
set -e
cd "$(dirname "$0")"
m68k-linux-gnu-as -mcpu=68000 --register-prefix-optional main.s -o main.o
m68k-linux-gnu-ld -e 0 -Ttext=0 main.o -o main.elf
m68k-linux-gnu-objcopy -O binary main.elf main.bin
{
    echo "// Generated by build.sh from main.s: the start of a stand-in for the Mega CD BIOS"
    echo "// (the rest of its 128 KB is zeroes) that starts the 32X as a Mega CD 32X game does."
    echo "#pragma once"
    echo "#include <cstdint>"
    echo "static const uint8_t kMegaCd32xProgram[] = {"
    od -An -v -tx1 main.bin | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g'
    echo "};"
} > megacd32x_program.h
rm -f main.o main.elf main.bin
