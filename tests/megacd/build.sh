#!/bin/sh
# Builds the Mega CD test program into megacd_program.h: the start of a stand-in BIOS
# for the console's 68000, with the sub CPU's program inside. Needs the 68000 binutils
# (Debian/Ubuntu: apt install binutils-m68k-linux-gnu). The header is committed, so
# the tests do not.
set -e
cd "$(dirname "$0")"
AS="m68k-linux-gnu-as -mcpu=68000 --register-prefix-optional"
LD="m68k-linux-gnu-ld -e 0 -Ttext=0"
$AS sub.s -o sub.o
$LD sub.o -o sub.elf
m68k-linux-gnu-objcopy -O binary sub.elf sub.bin
$AS main.s -o main.o
$LD main.o -o main.elf
m68k-linux-gnu-objcopy -O binary main.elf main.bin
{
    echo "// Generated by build.sh from main.s and sub.s: the start of a stand-in for the"
    echo "// Mega CD BIOS (the rest of its 128 KB is zeroes) that runs the test program on"
    echo "// both CPUs."
    echo "#pragma once"
    echo "#include <cstdint>"
    echo "static const uint8_t kMegaCdProgram[] = {"
    od -An -v -tx1 main.bin | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g'
    echo "};"
} > megacd_program.h
rm -f sub.o sub.elf sub.bin main.o main.elf main.bin
