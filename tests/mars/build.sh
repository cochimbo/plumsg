#!/bin/sh
# Builds the 32X test program into mars_program.h. Needs the SuperH cross compiler
# (Debian/Ubuntu: apt install gcc-sh-elf). The header is committed, so the tests do not.
set -e
cd "$(dirname "$0")"
sh-elf-gcc -m2 -mb -O2 -ffreestanding -nostdlib -fno-builtin -Wl,--no-warn-rwx-segments -T link.ld crt0.s program.c -lgcc -o program.elf
sh-elf-objcopy -O binary program.elf program.bin
{
    echo "// Generated by build.sh from program.c, checks.inc and crt0.s: the SH-2 side of"
    echo "// the 32X test program, to be loaded at 0x06000000."
    echo "#pragma once"
    echo "#include <cstdint>"
    echo "static const uint8_t kMarsProgram[] = {"
    od -An -v -tx1 program.bin | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g'
    echo "};"
} > mars_program.h
rm -f program.elf program.bin
