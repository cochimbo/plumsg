#!/usr/bin/env python3
"""Turns one of Anime4K's mpv shaders into src/render/anime4k_shaders.h.

Anime4K (https://github.com/bloc97/Anime4K, MIT) ships its networks as mpv "user
shaders": a list of passes, each a GLSL hook() that reads the textures it BINDs and
SAVEs its result under a name. This keeps each pass's code as it is and writes down
which textures it reads, which one it writes and whether it doubles the size; the
renderer supplies the mpv macros (NAME_tex, NAME_texOff, NAME_pos...) itself.

  tools/anime4k.py Anime4K_Upscale_CNN_x2_M.glsl > src/render/anime4k_shaders.h
"""

import sys


def passes(text):
    current = None
    for line in text.splitlines():
        if line.startswith("//!DESC"):
            current = {"desc": line[8:].strip(), "binds": [], "save": "", "doubles": False, "code": []}
            yield current
        elif current is None:
            continue
        elif line.startswith("//!BIND"):
            current["binds"].append(line.split()[1])
        elif line.startswith("//!SAVE"):
            current["save"] = line.split()[1]
        elif line.startswith("//!WIDTH"):
            current["doubles"] = line.rstrip().endswith("2 *")
        elif line.startswith("//!"):
            continue
        else:
            current["code"].append(line)


def main():
    with open(sys.argv[1], encoding="utf-8") as f:
        text = f.read()
    licence = []
    for line in text.splitlines():
        if line.startswith("//!"):
            break
        licence.append(line)
    while licence and not licence[-1].strip():
        licence.pop()
    out = ["#pragma once", "", "// Generated by tools/anime4k.py from " + sys.argv[1].split("/")[-1] + ".", "//"]
    out += licence
    out += ["", "namespace plumsg::anime4k {", "", "struct Pass {", "    const char* desc;",
            "    const char* binds[8];  // the textures it reads; \"MAIN\" is the picture",
            "    const char* save;      // the texture it writes; \"MAIN\" is the bigger picture",
            "    bool doubles;          // its result is twice as wide and high", "    const char* code;", "};", "",
            "constexpr Pass kPasses[] = {"]
    for p in list(passes(text)):
        binds = ", ".join('"%s"' % b for b in p["binds"])
        code = "\n".join(p["code"]).strip() + "\n"
        out.append('    {"%s", {%s}, "%s", %s, R"glsl(%s)glsl"},' % (p["desc"], binds, p["save"],
                                                                      "true" if p["doubles"] else "false", code))
    out += ["};", "", "}  // namespace plumsg::anime4k", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
